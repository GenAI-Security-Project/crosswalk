#!/usr/bin/env node
'use strict';
/**
 * backrefs.js — write the back-references that mapping files are missing.
 *
 * scripts/validate.js warns when mapping file A links mapping file B and B
 * does not link A. Rather than hand-add hundreds of reciprocal links (which
 * drift) or silence the check, this script generates them: each mapping file
 * that is linked from somewhere it does not itself link gets a block listing
 * those referring files.
 *
 * What it computes
 *   For every mapping file T (the same set validate.js checks, via
 *   scripts/crossrefs.js): the mapping files whose AUTHORED content links T,
 *   minus the files T's AUTHORED content already links, minus T itself.
 *   "Authored" means with existing back-reference blocks removed, so the
 *   output depends only on hand-written links and running twice is a no-op.
 *
 * Block format
 *     <!-- backrefs:start -->
 *
 *     ## Referenced by
 *
 *     (one-line note)
 *
 *     - [LLM_AIUC1.md](../llm-top10/LLM_AIUC1.md)
 *
 *     <!-- backrefs:end -->
 *   One relative link per referring file, link text = its file name, sorted
 *   by repository-relative path (plain code-unit order, so it is stable
 *   across locales and platforms).
 *
 * Placement rule
 *   Immediately before the file's first `## Changelog` heading, separated by
 *   one blank line on each side. A file with no Changelog heading (validate.js
 *   already fails such a file) gets the block at the end. When a file no
 *   longer needs a block, the block is removed and one blank line is left.
 *
 * Do not edit inside a block: fix the link in the referring file instead.
 *
 * Usage
 *   node scripts/backrefs.js           # rewrite blocks in place
 *   node scripts/backrefs.js --check   # exit 1 if any file would change
 *
 * Also run by scripts/generate.js, so CI's generator-reproducibility job
 * catches a stale block.
 */

const fs   = require('fs');
const path = require('path');
const {
  BACKREFS_START,
  BACKREFS_END,
  stripBackrefs,
  collectMappingFiles,
  buildCrossRefMap,
} = require('./crossrefs');

const ROOT = path.resolve(__dirname, '..');

const toPosix = (p) => p.split(path.sep).join('/');
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * target file → sorted array of the files that should appear in its block.
 * Only targets with at least one referrer are present.
 */
function computeBackrefs(root, files) {
  const authored = buildCrossRefMap(files, { authoredOnly: true });
  const inSet = new Set(Object.keys(authored));
  const result = new Map();
  for (const from of inSet) {
    for (const to of authored[from]) {
      if (to === from || !inSet.has(to)) continue;
      if (authored[to].has(from)) continue;
      if (!result.has(to)) result.set(to, []);
      result.get(to).push(from);
    }
  }
  for (const list of result.values()) {
    list.sort((a, b) => byCodeUnit(toPosix(path.relative(root, a)), toPosix(path.relative(root, b))));
  }
  return result;
}

/** The block for `target`, listing `referrers` (absolute paths). No surrounding newlines. */
function renderBlock(target, referrers) {
  const lines = [
    BACKREFS_START,
    '',
    '## Referenced by',
    '',
    // Two lines: markdownlint caps lines at 120 characters.
    'Mapping files that link to this one without a link back from it.',
    'Generated by `scripts/backrefs.js`; edit the links in those files, not this list.',
    '',
  ];
  for (const fp of referrers) {
    const href = toPosix(path.relative(path.dirname(target), fp));
    lines.push(`- [${path.basename(fp)}](${href})`);
  }
  lines.push('', BACKREFS_END);
  return lines.join('\n');
}

/**
 * Pure: `content` (LF) with its backrefs block replaced by `block`, or
 * removed when `block` is null.
 */
function applyBlock(content, block) {
  const base = stripBackrefs(content);
  if (!block) return base;
  // Exactly one blank line on each side, whatever was there before: that is
  // what stripBackrefs leaves behind, so a second run reproduces this output.
  const changelog = /^##\s+changelog/im.exec(base);
  if (changelog) {
    const head = base.slice(0, changelog.index).replace(/\n+$/, '');
    return (head ? head + '\n\n' : '') + block + '\n\n' + base.slice(changelog.index);
  }
  return base.replace(/\n+$/, '') + '\n\n' + block + '\n';
}

/**
 * Bring every mapping file under `root` up to date.
 * Returns the repository-relative paths of files that changed (or, with
 * `check`, would change). Files are rewritten only when their content
 * differs, keeping each file's existing line endings.
 */
function run({ root = ROOT, check = false } = {}) {
  const files = collectMappingFiles(root);
  const backrefs = computeBackrefs(root, files);
  const changed = [];
  for (const fp of files) {
    const target = path.resolve(fp);
    const raw = fs.readFileSync(fp, 'utf8');
    const crlf = raw.includes('\r\n');
    const current = raw.replace(/\r\n/g, '\n');
    const referrers = backrefs.get(target);
    const next = applyBlock(current, referrers ? renderBlock(target, referrers) : null);
    if (next === current) continue;
    changed.push(toPosix(path.relative(root, fp)));
    if (!check) fs.writeFileSync(fp, crlf ? next.replace(/\n/g, '\r\n') : next, 'utf8');
  }
  return changed;
}

module.exports = { computeBackrefs, renderBlock, applyBlock, run };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const changed = run({ check });
  if (check) {
    if (changed.length) {
      console.error(`backrefs: ${changed.length} file(s) out of date — run \`node scripts/backrefs.js\`:`);
      for (const f of changed) console.error(`  ${f}`);
      process.exit(1);
    }
    console.log('backrefs: all back-reference blocks are current');
  } else {
    console.log(`backrefs: ${changed.length} file(s) updated`);
    for (const f of changed) console.log(`  ${f}`);
  }
}
