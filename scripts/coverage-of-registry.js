#!/usr/bin/env node
/**
 * coverage-of-registry.js — Which registry items are actually used?
 *
 * The registries hold 1,514 line items. The crosswalk's mappings reference far
 * fewer. This report shows, per framework, how many registry items any entry
 * maps to and which are never referenced — the raw material for deciding where
 * coverage is genuinely thin versus where the registry is simply larger than
 * the mapped surface.
 *
 * `kind: layer` items are reported separately and excluded from the coverage
 * percentage: ENISA/MAESTRO layers are architecture context, not controls to
 * cover, and counting them drags every percentage down for no reason.
 *
 * Output: reports/coverage-of-registry.md   (reports/ is gitignored)
 *
 * Usage: node scripts/coverage-of-registry.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'reports');
const OUT = path.join(OUT_DIR, 'coverage-of-registry.md');

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const listJson = (dir) =>
  fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => path.join(dir, f));

// ── which control ids does any entry actually map? ───────────────────────────
const referenced = new Map(); // framework name -> Set(control_id)
for (const f of listJson(path.join(ROOT, 'data', 'entries'))) {
  for (const m of readJson(f).mappings || []) {
    if (!referenced.has(m.framework)) referenced.set(m.framework, new Set());
    referenced.get(m.framework).add(m.control_id);
  }
}

const registries = listJson(path.join(ROOT, 'data', 'frameworks')).map(readJson);

const rows = [];
const detail = [];

for (const r of registries.sort((a, b) => (a.name || a.id).localeCompare(b.name || b.id))) {
  const name = r.name || r.id;
  const items = r.controls || [];
  const used = referenced.get(name) || new Set();

  const coverable = items.filter((c) => c.kind !== 'layer');
  const layers = items.filter((c) => c.kind === 'layer');

  const hit = coverable.filter((c) => used.has(c.control_id));
  const miss = coverable.filter((c) => !used.has(c.control_id));

  // Ids a mapping cites that the registry does not contain — a broken join.
  const known = new Set(items.map((c) => c.control_id));
  const dangling = [...used].filter((id) => !known.has(id));

  const pct = coverable.length ? Math.round((hit.length / coverable.length) * 100) : 0;

  rows.push(
    `| ${name} | ${coverable.length} | ${hit.length} | ${miss.length} | ${pct}% | ` +
      `${layers.length || '—'} | ${dangling.length || '—'} |`,
  );

  detail.push({ name, miss, dangling, coverable: coverable.length, hit: hit.length });
}

const totalCoverable = detail.reduce((a, d) => a + d.coverable, 0);
const totalHit = detail.reduce((a, d) => a + d.hit, 0);
const totalDangling = detail.reduce((a, d) => a + d.dangling.length, 0);

const lines = [
  '# Registry coverage — referenced vs never-referenced',
  '',
  '*Generated by `scripts/coverage-of-registry.js`. Do not edit by hand.*',
  '',
  'How much of each framework registry the crosswalk actually maps to. `kind: layer`',
  'items (ENISA/MAESTRO architectural layers) are excluded from the coverage figure —',
  'they are context, not controls to cover — and reported in their own column.',
  '',
  `**Overall:** ${totalHit} of ${totalCoverable} coverable registry items are referenced by at least one mapping ` +
    `(${Math.round((totalHit / totalCoverable) * 100)}%).`,
  '',
  '| Framework | Coverable | Referenced | Never referenced | Coverage | Layers | Dangling |',
  '|---|--:|--:|--:|--:|--:|--:|',
  ...rows,
  '',
  '**Coverable** excludes `kind: layer`. **Dangling** counts control ids cited by a',
  'mapping that do not exist in the registry — those are broken joins, not coverage gaps.',
  '',
];

if (totalDangling) {
  lines.push('## Dangling references', '');
  lines.push('Mapping rows cite these ids, but the registry has no such item.', '');
  for (const d of detail.filter((x) => x.dangling.length)) {
    lines.push(`- **${d.name}** — ${d.dangling.length}: \`${d.dangling.slice(0, 12).join('`, `')}\`` +
      (d.dangling.length > 12 ? ` … +${d.dangling.length - 12} more` : ''));
  }
  lines.push('');
}

// ── join health: ids that are actually prose ─────────────────────────────────
// In several frameworks the mapping rows carry the requirement text in
// `control_id` and the real identifier in `control_name` — the two fields are
// swapped. Where the registry was extracted from those same rows the join still
// "works", so this is invisible to a coverage percentage but breaks any
// control-level lookup (and makes a per-row rationale meaningless).
const proseByFw = new Map();
let proseTotal = 0;
let mappingTotal = 0;
for (const f of listJson(path.join(ROOT, 'data', 'entries'))) {
  for (const m of readJson(f).mappings || []) {
    mappingTotal++;
    const cid = m.control_id || '';
    if (cid.length > 40 && (cid.match(/ /g) || []).length >= 5) {
      proseByFw.set(m.framework, (proseByFw.get(m.framework) || 0) + 1);
      proseTotal++;
    }
  }
}

if (proseTotal) {
  lines.push(
    '## Join health — `control_id` holding prose',
    '',
    `${proseTotal} of ${mappingTotal} mappings (${Math.round((proseTotal / mappingTotal) * 100)}%) ` +
      'carry requirement text in `control_id` where the identifier belongs; the real id sits in ' +
      '`control_name`. The two fields are swapped. Where a registry was extracted from these same ' +
      'rows the join still resolves, so coverage looks fine while control-level lookup is impossible.',
    '',
    '| Framework | Prose ids | Mappings |',
    '|---|--:|--:|',
    ...[...proseByFw.entries()]
      .sort((a, b) => b[1] - a[1])
      .map(([fw, n]) => `| ${fw} | ${n} | ${(referenced.get(fw) || new Set()).size} distinct |`),
    '',
    '> Not fixed here — swapping them back rewrites mapping rows, which belongs with the',
    '> schema-v2 migration (T-METH01) rather than a counting ticket.',
    '',
  );
}

lines.push('## Never-referenced items, by framework', '');
for (const d of detail.filter((x) => x.miss.length)) {
  lines.push(`### ${d.name} — ${d.miss.length} never referenced`, '');
  for (const c of d.miss.slice(0, 40)) {
    lines.push(`- \`${c.control_id}\` — ${(c.title || '').slice(0, 100)}`);
  }
  if (d.miss.length > 40) lines.push(`- *… +${d.miss.length - 40} more*`);
  lines.push('');
}

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(`Written reports/coverage-of-registry.md`);
console.log(
  `  ${totalHit}/${totalCoverable} coverable items referenced ` +
    `(${Math.round((totalHit / totalCoverable) * 100)}%)` +
    (totalDangling ? ` · ${totalDangling} dangling reference(s)` : ''),
);
