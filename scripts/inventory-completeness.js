#!/usr/bin/env node
/**
 * inventory-completeness.js — Disclose how complete each framework registry is.
 *
 * The registries are partial. `data/frameworks/iso-27001.json` holds 54
 * controls; ISO 27001:2022 Annex A has considerably more. Nothing said so, and
 * every coverage percentage in the reports and the webapp was therefore
 * computed against an incomplete denominator and read falsely green.
 *
 * This annotates each registry with an `inventory_completeness` block and emits
 * a research list for the totals that cannot be established here.
 *
 * On `total: null` — deliberate, not lazy. Several of these standards are
 * paywalled (ISO, IEC, ISA), so their authoritative control counts cannot be
 * verified from this environment. Writing a number from memory is precisely the
 * unverified assertion this ticket exists to eliminate, so unverified totals are
 * recorded as unknown and listed for a human with access.
 *
 * One inference is drawn rather than guessed: a registry whose items are *all*
 * referenced by mappings was extracted from those mappings, so by construction
 * it cannot contain the framework's unmapped controls. Those are `partial`
 * regardless of what their true total turns out to be.
 *
 * Usage:
 *   node scripts/inventory-completeness.js            # annotate + report
 *   node scripts/inventory-completeness.js --check    # fail if any registry lacks the field
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const FW_DIR = path.join(ROOT, 'data', 'frameworks');
const OUT_DIR = path.join(ROOT, 'reports');
const OUT = path.join(OUT_DIR, 'inventory-completeness.md');

const CHECK = process.argv.includes('--check');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

/**
 * Registries whose inventory is complete by construction, with the reason.
 * Nothing goes here without one.
 */
const COMPLETE_BY_DEFINITION = {
  STRIDE: 'STRIDE is a closed six-element mnemonic; all six are present.',
};

// ── which control ids do mappings actually cite? ─────────────────────────────
const cited = new Map();
const entryDir = path.join(ROOT, 'data', 'entries');
for (const f of fs.readdirSync(entryDir).filter((n) => n.endsWith('.json'))) {
  for (const m of readJson(path.join(entryDir, f)).mappings || []) {
    if (!cited.has(m.framework)) cited.set(m.framework, new Set());
    cited.get(m.framework).add(m.control_id);
  }
}

const rows = [];
let missing = 0;

for (const file of fs.readdirSync(FW_DIR).filter((n) => n.endsWith('.json'))) {
  const p = path.join(FW_DIR, file);
  const reg = readJson(p);
  const name = reg.name || reg.id;
  const items = reg.controls || [];
  const controls = items.filter((c) => c.kind === 'control');
  const included = controls.length || items.length;

  if (CHECK) {
    if (!reg.inventory_completeness) {
      console.error(`✗ ${file} has no inventory_completeness block`);
      missing++;
    }
    continue;
  }

  const used = cited.get(name) || new Set();
  const allReferenced = items.length > 0 && items.every((c) => used.has(c.control_id));

  let status, total, note;
  if (COMPLETE_BY_DEFINITION[name]) {
    status = 'complete';
    total = included;
    note = COMPLETE_BY_DEFINITION[name];
  } else if (allReferenced) {
    status = 'partial';
    total = null;
    note =
      'Every item in this registry is referenced by a mapping, so the registry was ' +
      'derived from the mappings rather than from the framework. It cannot contain ' +
      'controls this crosswalk has not mapped. Authoritative total not yet established.';
  } else {
    status = 'unknown';
    total = null;
    note =
      'Authoritative control count not established. ' +
      (/ISO|IEC|ISA|PCI/i.test(name)
        ? 'The standard is paywalled, so the total cannot be verified from a public source here.'
        : 'Needs a count from the published framework.');
  }

  reg.inventory_completeness = {
    status,
    included,
    total,
    note,
    source: reg.url || null,
  };
  fs.writeFileSync(p, JSON.stringify(reg, null, 2) + '\n', 'utf8');

  rows.push({ name, file, status, included, total, note });
}

if (CHECK) {
  if (missing) {
    console.error(`✗ ${missing} registry/registries missing inventory_completeness`);
    process.exit(1);
  }
  console.log('✓ every registry declares inventory_completeness');
  process.exit(0);
}

// ── report ───────────────────────────────────────────────────────────────────
rows.sort((a, b) => a.name.localeCompare(b.name));
const byStatus = (s) => rows.filter((r) => r.status === s);

const lines = [
  '# Inventory completeness — how much of each framework is actually in the registry',
  '',
  '*Generated by `scripts/inventory-completeness.js`. Do not edit by hand.*',
  '',
  'Coverage percentages are only meaningful against a known denominator. These',
  'registries are partial, and until now nothing said so — so every coverage score',
  'was computed against an incomplete inventory and read greener than the truth.',
  '',
  `**${byStatus('complete').length} complete · ${byStatus('partial').length} known partial · ` +
    `${byStatus('unknown').length} unknown**`,
  '',
  '| Framework | Status | In registry | Framework total | ',
  '|---|---|--:|--:|',
  ...rows.map((r) => `| ${r.name} | \`${r.status}\` | ${r.included} | ${r.total ?? '—'} |`),
  '',
  '## Why so many totals are unknown',
  '',
  'Writing a control count from memory is the same class of unverified assertion',
  'this annotation exists to remove. Where the authoritative total could not be',
  'established from a public source, it is recorded as unknown rather than guessed.',
  '',
  '`partial` is asserted where it follows from the data: if every item in a registry',
  'is referenced by a mapping, the registry was built from the mappings and cannot',
  'contain the framework\'s unmapped controls.',
  '',
  '## Research list — needs a human with access to the published standard',
  '',
  '| Framework | In registry | Source |',
  '|---|--:|---|',
  ...rows
    .filter((r) => r.total === null)
    .map((r) => `| ${r.name} | ${r.included} | ${r.file} |`),
  '',
  'Fill `inventory_completeness.total` in the registry file and re-run this script.',
  '',
];

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log('Written reports/inventory-completeness.md');
console.log(
  `  ${byStatus('complete').length} complete · ${byStatus('partial').length} partial · ` +
    `${byStatus('unknown').length} unknown · ${rows.filter((r) => r.total === null).length} totals to research`,
);
